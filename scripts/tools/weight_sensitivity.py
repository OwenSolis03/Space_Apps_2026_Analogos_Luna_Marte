#!/usr/bin/env python3
"""How much does the ranking depend on the preset weights?

For every mission case and every target that case ranks, the exported analogs are re-ranked with perturbed
weights and compared with the ranking under the published weights. Same MSI rule as the pipeline and the app:
dimensions the target does not have are ignored, and a dimension the target has but the Earth patch lacks
counts as the policy's ``earth_missing_score``.

Two tests:

* ``near``: each non-zero weight is multiplied by exp(sigma * N(0, 1)) with sigma 0.4 (about plus or minus 50%).
  Zero weights stay zero. Answers: "is the result stable if the numbers are a bit different?"
* ``random``: weights drawn uniformly from the simplex over the dimensions that apply to the target (Dirichlet(1)).
  Answers: "how much does the choice of weights matter at all?" This is the upper bound of the sensitivity.

Limit: only the analogs that the export keeps (30 per case, union over cases) are re-ranked, not the whole Earth,
so the numbers describe ranking inside that pool.

    python tools/weight_sensitivity.py app/public/data/analogs_universe.json --out docs/weight_sensitivity.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

DIMS = ["topography", "roughness", "environment", "thermal", "geology", "dust", "ice"]


def msi_matrix(analogs: list[dict], dims: list[str], earth_missing: float) -> np.ndarray:
    """(n_analogs, n_dims) sub-scores, with Earth-missing dimensions already set to ``earth_missing``."""
    out = np.zeros((len(analogs), len(dims)))
    for i, a in enumerate(analogs):
        for j, d in enumerate(dims):
            s = a["sub_scores"].get(d)
            out[i, j] = earth_missing if s is None else s
    return out


def ranks(values: np.ndarray) -> np.ndarray:
    order = np.argsort(-values, kind="mergesort")
    r = np.empty(len(values))
    r[order] = np.arange(len(values))
    return r


def spearman(a: np.ndarray, b: np.ndarray) -> float:
    ra, rb = ranks(a), ranks(b)
    if ra.std() == 0 or rb.std() == 0:
        return float("nan")
    return float(np.corrcoef(ra, rb)[0, 1])


def top_overlap(base: np.ndarray, other: np.ndarray, k: int) -> float:
    k = min(k, len(base))
    return len(set(np.argsort(-base, kind="mergesort")[:k]) & set(np.argsort(-other, kind="mergesort")[:k])) / k


def run(universe: dict, draws: int, seed: int) -> list[dict]:
    rng = np.random.default_rng(seed)
    earth_missing = universe["metadata"].get("scoring_policy", {}).get("earth_missing_score", 0.0)
    rows = []
    for pkey, preset in universe["mission_presets"].items():
        base_w = {d: float(preset["weights"].get(d, 0.0)) for d in DIMS}
        acc = {"near": {"t5": [], "t10": [], "rho": [], "top1_in_top3": []}, "random": {"t5": [], "t10": [], "rho": [], "top1_in_top3": []}}
        n_targets = 0
        for t in universe["targets"]:
            status = t.get("preset_status", {}).get(pkey, {}).get("status")
            if status != "ok":
                continue
            dims = [d for d in t["available_dims"] if d in DIMS]
            analogs = [a for a in t["analogs"] if a["msi_by_preset"].get(pkey) is not None]
            if len(analogs) < 10:
                continue
            n_targets += 1
            S = msi_matrix(analogs, dims, earth_missing)
            w0 = np.array([base_w[d] for d in dims])
            if w0.sum() <= 0:
                continue
            base = S @ (w0 / w0.sum())
            for _ in range(draws):
                nz = w0 > 0
                w_near = np.where(nz, w0 * np.exp(0.4 * rng.standard_normal(len(dims))), 0.0)
                w_rand = rng.dirichlet(np.ones(len(dims)))
                for name, w in (("near", w_near), ("random", w_rand)):
                    other = S @ (w / w.sum())
                    a_ = acc[name]
                    a_["t5"].append(top_overlap(base, other, 5))
                    a_["t10"].append(top_overlap(base, other, 10))
                    a_["rho"].append(spearman(base, other))
                    best = int(np.argmax(base))
                    a_["top1_in_top3"].append(float(best in np.argsort(-other, kind="mergesort")[:3]))
        if n_targets:
            rows.append({
                "preset": pkey, "label": preset["label"], "targets": n_targets, "weights": base_w,
                **{f"{n}_{m}": float(np.nanmean(v)) for n, d in acc.items() for m, v in d.items()},
            })
    return rows


def markdown(rows: list[dict], draws: int, seed: int) -> str:
    lines = [
        "# Weight sensitivity of the mission cases", "",
        f"Generated by `tools/weight_sensitivity.py` ({draws} draws per target, seed {seed}). Each cell is the mean over the targets the case ranks and over the draws.", "",
        "| Mission case | Targets | `near`: top-5 kept | `near`: top-10 kept | `near`: rank correlation | `random`: top-10 kept | `random`: rank correlation |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        lines.append(
            f"| {r['label']} | {r['targets']} | {r['near_t5'] * 100:.0f}% | {r['near_t10'] * 100:.0f}% | {r['near_rho']:.2f} | "
            f"{r['random_t10'] * 100:.0f}% | {r['random_rho']:.2f} |"
        )
    lines += [
        "", "`near`: each non-zero weight multiplied by exp(0.4 z), about plus or minus 50%, zero weights stay zero.",
        "`random`: any weights over the dimensions that apply to the target (uniform on the simplex).",
        "Top-k kept: share of the best k analogs under the published weights that are still among the best k.",
        "Rank correlation: Spearman between the two rankings of the target's exported analogs.", "",
    ]
    return "\n".join(lines)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("universe", type=Path)
    p.add_argument("--draws", type=int, default=300)
    p.add_argument("--seed", type=int, default=2026)
    p.add_argument("--out", type=Path)
    args = p.parse_args()
    universe = json.loads(args.universe.read_text(encoding="utf-8"))
    text = markdown(run(universe, args.draws, args.seed), args.draws, args.seed)
    print(text)
    if args.out:
        args.out.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
